-- Esquema privado para funciones internas: no está expuesto por la Data API.
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

-- Texto normalizado para búsqueda: minúsculas y sin tildes (igual que normalize() en el front).
create or replace function private.normalize_search(input text)
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$
  select lower(translate(coalesce(input, ''), 'ÁÉÍÓÚÜÑáéíóúüñ', 'AEIOUUNaeiouun'))
$$;

-- -----------------------------------------------------------------------------
-- categories
-- -----------------------------------------------------------------------------
create table if not exists public.categories (
  id          smallint generated by default as identity primary key,
  slug        text not null,
  name        text not null,
  description text not null default '',
  sort_order  smallint not null default 0,
  constraint categories_slug_key unique (slug),
  constraint categories_slug_format check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 60),
  constraint categories_name_length check (char_length(name) between 1 and 80),
  constraint categories_description_length check (char_length(description) <= 300)
);

-- -----------------------------------------------------------------------------
-- products
-- -----------------------------------------------------------------------------
create table if not exists public.products (
  id               uuid primary key default gen_random_uuid(),
  slug             text not null,
  name             text not null,
  description      text not null default '',
  details          text[] not null default '{}',
  care             text[] not null default '{}',
  material         text not null default '',
  category_id      smallint not null,
  price_cents      integer not null,
  compare_at_cents integer,
  is_new           boolean not null default false,
  is_active        boolean not null default true,
  -- 0–100, ordena por "Relevancia"
  popularity       smallint not null default 0,
  -- Lo mantiene el trigger products_search_text: nombre, descripción, material, categoría y colores
  search_text      text not null default '',
  created_at       timestamptz not null default now(),
  constraint products_slug_key unique (slug),
  constraint products_category_id_fkey foreign key (category_id) references public.categories (id) on delete restrict,
  constraint products_slug_format check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 120),
  constraint products_name_length check (char_length(name) between 1 and 120),
  constraint products_description_length check (char_length(description) <= 2000),
  constraint products_details_length check (cardinality(details) <= 20 and char_length(array_to_string(details, '')) <= 2000),
  constraint products_care_length check (cardinality(care) <= 10 and char_length(array_to_string(care, '')) <= 1000),
  constraint products_material_length check (char_length(material) <= 200),
  constraint products_price_positive check (price_cents > 0),
  constraint products_compare_at_gt_price check (compare_at_cents is null or compare_at_cents > price_cents),
  constraint products_popularity_range check (popularity between 0 and 100)
);

-- slug: cubierto por el índice único products_slug_key
create index if not exists products_category_id_idx on public.products (category_id);
create index if not exists products_active_popularity_idx on public.products (popularity desc) where is_active;
create index if not exists products_price_idx on public.products (price_cents);
create index if not exists products_created_at_idx on public.products (created_at desc);

-- -----------------------------------------------------------------------------
-- product_colors
-- -----------------------------------------------------------------------------
create table if not exists public.product_colors (
  id         bigint generated by default as identity primary key,
  product_id uuid not null,
  -- Clave del color compartida entre productos ("negro", "crudo"…): la usa el filtro ?color=
  slug       text not null,
  name       text not null,
  hex        text not null,
  sort_order smallint not null default 0,
  constraint product_colors_product_id_fkey foreign key (product_id) references public.products (id) on delete cascade,
  constraint product_colors_product_slug_key unique (product_id, slug),
  -- Destino de las FK compuestas de variants e images (el color tiene que ser del mismo producto)
  constraint product_colors_id_product_key unique (id, product_id),
  constraint product_colors_slug_format check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 40),
  constraint product_colors_name_length check (char_length(name) between 1 and 60),
  constraint product_colors_hex_format check (hex ~ '^#[0-9A-Fa-f]{6}$')
);

-- product_id: cubierto por product_colors_product_slug_key (product_id es la primera columna)
create index if not exists product_colors_slug_idx on public.product_colors (slug);

-- -----------------------------------------------------------------------------
-- product_images  (color_id null = la foto sirve para todos los colores)
-- -----------------------------------------------------------------------------
create table if not exists public.product_images (
  id         bigint generated by default as identity primary key,
  product_id uuid not null,
  color_id   bigint,
  view       text not null,
  -- Ruta relativa a la raíz del sitio, p. ej. images/products/vestido-midi-lino-1.jpg
  path       text not null,
  width      integer not null,
  height     integer not null,
  alt        text not null,
  sort_order smallint not null default 0,
  constraint product_images_product_id_fkey foreign key (product_id) references public.products (id) on delete cascade,
  constraint product_images_color_fkey foreign key (color_id, product_id)
    references public.product_colors (id, product_id) on delete cascade,
  constraint product_images_product_path_key unique (product_id, path),
  constraint product_images_view_check check (view in ('frente', 'espalda', 'detalle')),
  constraint product_images_path_format check (
    char_length(path) between 1 and 300 and path !~ '^(/|[a-z]+:)' and path !~ '\.\.'
  ),
  constraint product_images_size_check check (width between 1 and 10000 and height between 1 and 10000),
  constraint product_images_alt_length check (char_length(alt) between 1 and 300)
);

-- product_id: cubierto por product_images_product_path_key
create index if not exists product_images_color_id_idx on public.product_images (color_id);

-- -----------------------------------------------------------------------------
-- variants
-- -----------------------------------------------------------------------------
create table if not exists public.variants (
  id         bigint generated by default as identity primary key,
  product_id uuid not null,
  color_id   bigint not null,
  size       text not null,
  sku        text not null,
  stock      integer not null default 0,
  constraint variants_product_id_fkey foreign key (product_id) references public.products (id) on delete cascade,
  constraint variants_color_fkey foreign key (color_id, product_id)
    references public.product_colors (id, product_id) on delete cascade,
  constraint variants_sku_key unique (sku),
  constraint variants_product_color_size_key unique (product_id, color_id, size),
  constraint variants_size_check check (size in ('XS', 'S', 'M', 'L', 'XL')),
  constraint variants_sku_format check (sku ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(sku) <= 64),
  constraint variants_stock_nonnegative check (stock >= 0)
);

-- product_id: cubierto por variants_product_color_size_key
create index if not exists variants_color_id_idx on public.variants (color_id);
create index if not exists variants_in_stock_idx on public.variants (product_id, size) where stock > 0;

-- -----------------------------------------------------------------------------
-- Búsqueda: products.search_text se recalcula al cambiar el producto o sus colores
-- -----------------------------------------------------------------------------
create or replace function private.products_set_search_text()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.search_text := private.normalize_search(concat_ws(' ',
    new.name,
    new.description,
    new.material,
    (select c.slug || ' ' || c.name from public.categories c where c.id = new.category_id),
    (select string_agg(pc.name, ' ') from public.product_colors pc where pc.product_id = new.id)
  ));
  return new;
end
$$;

create or replace function private.product_colors_touch_product()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  -- Un UPDATE "vacío" dispara products_search_text y recalcula el texto
  if tg_op in ('UPDATE', 'DELETE') then
    update public.products set search_text = search_text where id = old.product_id;
  end if;
  if tg_op in ('INSERT', 'UPDATE') then
    update public.products set search_text = search_text where id = new.product_id;
  end if;
  return null;
end
$$;

drop trigger if exists products_search_text on public.products;
create trigger products_search_text
  before insert or update on public.products
  for each row execute function private.products_set_search_text();

drop trigger if exists product_colors_search_text on public.product_colors;
create trigger product_colors_search_text
  after insert or update or delete on public.product_colors
  for each row execute function private.product_colors_touch_product();

revoke all on all functions in schema private from public, anon, authenticated;
