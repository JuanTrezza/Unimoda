-- =============================================================================
-- 0002 · Formularios: newsletter y contacto
-- Idempotente. Las validaciones viven en CHECK: el cliente no puede saltearlas.
-- =============================================================================

create table if not exists public.newsletter_subscribers (
  id         bigint generated by default as identity primary key,
  email      text not null,
  created_at timestamptz not null default now(),
  constraint newsletter_subscribers_email_key unique (email),
  -- Se guarda en minúsculas y sin espacios: así el unique no deja pasar "Ana@Mail.com" y "ana@mail.com"
  constraint newsletter_subscribers_email_normalized check (email = lower(btrim(email))),
  constraint newsletter_subscribers_email_format check (
    char_length(email) between 6 and 254
    and email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]{2,}$'
  )
);

create table if not exists public.contact_messages (
  id         bigint generated by default as identity primary key,
  name       text not null,
  email      text not null,
  message    text not null,
  created_at timestamptz not null default now(),
  constraint contact_messages_name_length check (char_length(btrim(name)) between 2 and 100),
  constraint contact_messages_email_format check (
    char_length(email) between 6 and 254
    and email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]{2,}$'
  ),
  constraint contact_messages_message_length check (char_length(btrim(message)) between 10 and 5000)
);

create index if not exists contact_messages_created_at_idx on public.contact_messages (created_at desc);
